"""``docs/data/``: one data card per adapter, rendered from the code.

``craton data cards`` writes them; ``craton check`` re-renders and fails on any difference, so
a card can't drift from the adapter it describes.
"""

from __future__ import annotations

from pathlib import Path

from craton.adapters import ADAPTERS, get_adapter
from craton.adapters.base import DataCard
from craton.paths import data_docs_dir

HEADER = "<!-- Generated by `craton data cards` from craton/adapters/. Do not edit by hand. -->\n"


def render_card(card: DataCard) -> str:
    lines = [
        HEADER,
        f"# {card.title}",
        "",
        f"`{card.name}` · adapter {card.adapter_version} · makes "
        + ", ".join(f"`{i}`" for i in card.instruments)
        + " tokens",
        "",
        "| | |",
        "|---|---|",
        f"| Provider | {card.provider} |",
        f"| Home | {card.homepage} |",
        f"| Licence | `{card.license}` |",
        "",
        "## Terms",
        "",
        card.terms,
        "",
        "## Cite",
        "",
        *[f"- {c}" for c in card.citations],
        "",
        "## Access",
        "",
        card.access,
        "",
        "## From the source to the token",
        "",
        "| Token slot | Comes from |",
        "|---|---|",
        *[f"| `{slot}` | {src} |" for slot, src in card.mapping],
        "",
        "## Uncertainty",
        "",
        card.uncertainty,
        "",
        "## Known issues",
        "",
        *[f"- {issue}" for issue in card.known_issues],
        "",
    ]
    return "\n".join(lines)


def render_index() -> str:
    lines = [
        HEADER,
        "# Data cards",
        "",
        "Every source Craton reads, who made it, under what terms, and what to watch out for. "
        "Licences and citations travel with the data: each token carries its licence in "
        "`provenance.license` and the hash of the raw file it came from.",
        "",
        "| Adapter | Source | Tokens | Licence |",
        "|---|---|---|---|",
    ]
    for name in sorted(ADAPTERS):
        c = get_adapter(name).card()
        insts = ", ".join(f"`{i}`" for i in c.instruments)
        lines.append(f"| [`{name}`]({name}.md) | {c.title} | {insts} | `{c.license}` |")
    lines.append("")
    return "\n".join(lines)


def rendered() -> dict[str, str]:
    out = {"README.md": render_index()}
    for name in sorted(ADAPTERS):
        out[f"{name}.md"] = render_card(get_adapter(name).card())
    return out


def write(root: Path) -> list[Path]:
    folder = data_docs_dir(root)
    folder.mkdir(parents=True, exist_ok=True)
    paths = []
    for fname, text in rendered().items():
        p = folder / fname
        p.write_text(text, encoding="utf-8", newline="\n")
        paths.append(p)
    return paths


def drift_problems(root: Path) -> list[str]:
    folder = data_docs_dir(root)
    problems = []
    for fname, text in rendered().items():
        p = folder / fname
        if not p.is_file() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            problems.append(f"docs/data/{fname} is out of date; run `craton data cards`")
    return problems
