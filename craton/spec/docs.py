"""``docs/token-spec.md``, rendered from the code so the two can never disagree.

``craton spec docs`` writes it; ``craton check`` re-renders it and fails on any difference.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from craton.spec.examples import EXAMPLES, ILLUSTRATIVE, example
from craton.spec.instruments import REGISTRY
from craton.spec.registry import UNITS
from craton.spec.token import SPEC_VERSION

HEADER = "<!-- Generated by `craton spec docs` from craton/spec/. Do not edit by hand. -->\n"

SLOTS = [
    ("kind", "observation · forcing · property · event · derived", "What sort of thing it is."),
    ("instrument", "a registered name", "Says what the numbers in `value` mean."),
    ("lat, lon", "WGS84 degrees; lon in [-180, 180)", "Where."),
    ("depth_km", "km below the WGS84 ellipsoid", "Negative is above it: a station on a hill."),
    ("time", "seconds since 1970-01-01T00:00:00Z", "Proleptic Gregorian, ±4.6 billion years."),
    ("time_iso", "ISO 8601, optional", "The same moment for humans; must agree with `time`."),
    ("value", "list of numbers", "One per channel of the instrument."),
    ("uncertainty", "list of numbers > 0", "1σ per channel. Never zero."),
    ("uncertainty_basis", "reported · derived · assumed", "Where the uncertainty came from."),
    ("location_uncertainty", "optional, 1σ", "How well *where and when* are known."),
    ("qualifiers", "text labels", "Magnitude type, station code, intensity scale…"),
    ("provenance", "source, version, licence, hash…", "Enough to fetch the same bytes again."),
    ("resolution", "spatial_km, temporal_s", "How big a patch of space and time one value covers."),
]


def _num(x: float) -> str:
    if math.isinf(x):
        return "∞" if x > 0 else "−∞"
    return f"{x:g}"


def render() -> str:
    lines = [
        HEADER,
        f"# Token Spec {SPEC_VERSION}",
        "",
        "One shape for every measurement on Earth. What may change between versions (only "
        "additions) is in [`SPEC_POLICY.md`](../SPEC_POLICY.md).",
        "",
        "## The slots",
        "",
        "| Slot | Holds | Why |",
        "|---|---|---|",
    ]
    lines += [f"| `{a}` | {b} | {c} |" for a, b, c in SLOTS]
    lines += ["", "## Instruments", ""]
    for inst in REGISTRY:
        lines += [
            f"### `{inst.name}`",
            "",
            f"{inst.description}",
            "",
            f"Kinds: {', '.join(f'`{k}`' for k in inst.kinds)}"
            + (
                " · the channels are probabilities and sum to 1"
                if inst.constraint == "simplex"
                else ""
            )
            + f" · added in {inst.added_in}",
            "",
            "| Channel | Unit | Range | Meaning |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| `{c.name}` | `{c.unit}` | {_num(c.minimum)} … {_num(c.maximum)} | {c.description} |"
            for c in inst.channels
        ]
        if inst.qualifiers:
            lines += ["", "| Qualifier | Required | Allowed | Meaning |", "|---|---|---|---|"]
            for q in inst.qualifiers:
                if q.vocabulary:
                    allowed = ", ".join(f"`{v}`" for v in q.vocabulary)
                elif q.pattern:
                    allowed = f"pattern `{q.pattern}`"
                else:
                    allowed = "any short text"
                req = "yes" if q.required else "no"
                lines.append(f"| `{q.name}` | {req} | {allowed} | {q.description} |")
        if inst.references:
            lines += ["", "References: " + "; ".join(inst.references)]
        lines.append("")
    lines += ["## Units", "", "| Code | Meaning |", "|---|---|"]
    lines += [f"| `{k}` | {v} |" for k, v in UNITS.items()]
    lines += [
        "",
        "## Examples",
        "",
        f"One per kind, plus the monk. Tokens marked *{ILLUSTRATIVE}* show the shape only. "
        "Print any of them with `craton spec example NAME`.",
        "",
    ]
    for name in EXAMPLES:
        tok = example(name)
        lines += [
            f"### `{name}` · {tok.kind}",
            "",
            "```json",
            json.dumps(tok.to_dict(), indent=2, ensure_ascii=False),
            "```",
            "",
        ]
    return "\n".join(lines)


def path(root: Path) -> Path:
    return root / "docs" / "token-spec.md"


def write(root: Path) -> Path:
    out = path(root)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8", newline="\n")
    return out


def drift_problem(root: Path) -> str | None:
    out = path(root)
    if not out.exists():
        return "docs/token-spec.md is missing; run `craton spec docs`"
    if out.read_text(encoding="utf-8").replace("\r\n", "\n") != render():
        return "docs/token-spec.md is out of date with the code; run `craton spec docs`"
    return None
